import {
  CLIP_DURATION_OPTIONS,
  DEFAULT_CLIP_DURATION,
  type AspectRatioOption,
  type ClipDurationOption,
} from '../types/studio';

export interface ParsedMp4Metadata {
  durationSeconds: number;
  timescale: number;
  frameCount?: number;
  fps?: number;
}

export function isValidClipDuration(value: unknown): value is ClipDurationOption {
  return (
    typeof value === 'number' &&
    (CLIP_DURATION_OPTIONS as readonly number[]).includes(value)
  );
}

export function normalizeClipDuration(value: unknown): ClipDurationOption {
  const numeric = Number(value);
  if (isValidClipDuration(numeric)) {
    return numeric;
  }
  return DEFAULT_CLIP_DURATION;
}

/**
 * Computes the exact frame count generated by Lightricks LTX-2.3 / LTX-Video at 24 FPS:
 * LTX temporal VAE requires frames = 8 * k + 1, so:
 *   4s -> 97 frames (4.04s @ 24 FPS)
 *   6s -> 145 frames (6.04s @ 24 FPS)
 *   8s -> 193 frames (8.04s @ 24 FPS)
 *   10s -> 241 frames (10.04s @ 24 FPS)
 */
export function getExpectedLtxFrameCount(duration: ClipDurationOption, fps = 24): number {
  return Math.floor((Math.floor(duration * fps) + 7) / 8) * 8 + 1;
}

/**
 * Returns 64-pixel-aligned spatial dimensions required by LTX-2.3 two-stage DistilledPipeline.
 * Accounts for ZeroGPU's 1.5x hardware duration multiplier so unauthenticated requests keep
 * GPU reservations low across 4s, 6s, 8s, and 10s without truncating frames or looping.
 */
export function getLtx23Dimensions(
  aspectRatio: AspectRatioOption,
  duration: ClipDurationOption,
  authenticatedQuota = false,
  compactRetry = false
): { width: number; height: number } {
  if (compactRetry) {
    switch (aspectRatio) {
      case '9:16':
        return { width: 256, height: 384 };
      case '1:1':
        return { width: 256, height: 256 };
      case '4:3':
        return { width: 320, height: 256 };
      case '16:9':
      default:
        return { width: 384, height: 256 };
    }
  }

  if (authenticatedQuota) {
    switch (aspectRatio) {
      case '9:16':
        return { width: 512, height: 768 };
      case '1:1':
        return { width: 640, height: 640 };
      case '4:3':
        return { width: 704, height: 512 };
      case '16:9':
      default:
        return { width: 768, height: 512 };
    }
  }

  if (duration === 4) {
    switch (aspectRatio) {
      case '9:16':
        return { width: 384, height: 640 };
      case '1:1':
        return { width: 512, height: 512 };
      case '4:3':
        return { width: 576, height: 448 };
      case '16:9':
      default:
        return { width: 640, height: 384 };
    }
  }

  if (duration === 6) {
    switch (aspectRatio) {
      case '9:16':
        return { width: 320, height: 576 };
      case '1:1':
        return { width: 448, height: 448 };
      case '4:3':
        return { width: 512, height: 384 };
      case '16:9':
      default:
        return { width: 576, height: 320 };
    }
  }

  if (duration === 8) {
    switch (aspectRatio) {
      case '9:16':
        return { width: 320, height: 512 };
      case '1:1':
        return { width: 384, height: 384 };
      case '4:3':
        return { width: 448, height: 320 };
      case '16:9':
      default:
        return { width: 512, height: 320 };
    }
  }

  // 10s unauthenticated ZeroGPU budget (241 frames @ 24 FPS, 64px-aligned)
  switch (aspectRatio) {
    case '9:16':
      return { width: 256, height: 448 };
    case '1:1':
      return { width: 320, height: 320 };
    case '4:3':
      return { width: 384, height: 320 };
    case '16:9':
    default:
      return { width: 448, height: 256 };
  }
}

/**
 * Resolves Gradio 4/5/6 video FileData objects into a clean HTTPS URL.
 * Prevents Mixed-Content `http://` failures and broken root-relative `/gradio_api/file=...` paths.
 */
export function normalizeGradioVideoUrl(options: {
  rawUrl?: string | null;
  rawPath?: string | null;
  spaceBase: string;
  apiPrefix: '/gradio_api' | '';
}): string | undefined {
  const cleanBase = options.spaceBase.replace(/\/+$/, '');
  const filePrefix = options.apiPrefix ? `${options.apiPrefix}/file=` : '/file=';

  const candidates = [options.rawUrl, options.rawPath].filter(
    (v): v is string => typeof v === 'string' && v.trim().length > 0
  );

  for (const raw of candidates) {
    const trimmed = raw.trim();

    if (trimmed.startsWith('https://')) {
      return trimmed;
    }

    if (trimmed.startsWith('http://')) {
      try {
        const parsed = new URL(trimmed);
        if (parsed.hostname.endsWith('.hf.space') || parsed.hostname.endsWith('huggingface.co')) {
          parsed.protocol = 'https:';
          return parsed.toString();
        }
        if (parsed.hostname === 'localhost' || parsed.hostname === '127.0.0.1' || parsed.hostname === '0.0.0.0') {
          return `${cleanBase}${parsed.pathname}${parsed.search}`;
        }
      } catch {
        // Continue to next candidate
      }
    }

    if (
      trimmed.startsWith('/gradio_api/file=') ||
      trimmed.startsWith('/file=')
    ) {
      return `${cleanBase}${trimmed}`;
    }

    // Filesystem path returned by Gradio (e.g. "/tmp/gradio/..." or "outputs/...")
    if (trimmed.startsWith('/') || trimmed.endsWith('.mp4') || trimmed.endsWith('.webm')) {
      return `${cleanBase}${filePrefix}${trimmed}`;
    }
  }

  return undefined;
}

const CONTAINER_BOX_TYPES = new Set([
  'moov',
  'trak',
  'mdia',
  'minf',
  'stbl',
  'edts',
  'udta',
]);

/**
 * Checks if a binary buffer starts with an ISO BMFF (`ftyp`/`moov`/`mdat`) or WebM (`0x1A45DFA3`) header.
 */
export function hasValidVideoSignature(bytes: Uint8Array): boolean {
  if (bytes.byteLength < 12) return false;
  const fourCc = String.fromCharCode(bytes[4], bytes[5], bytes[6], bytes[7]);
  if (fourCc === 'ftyp' || fourCc === 'moov' || fourCc === 'mdat' || fourCc === 'wide' || fourCc === 'free') {
    return true;
  }
  // WebM / Matroska EBML magic bytes
  if (bytes[0] === 0x1a && bytes[1] === 0x45 && bytes[2] === 0xdf && bytes[3] === 0xa3) {
    return true;
  }
  return false;
}

/**
 * Parses ISO BMFF (MP4/MOV) boxes (`mvhd`, `hdlr`, and `stts`) directly from a binary buffer
 * to verify real container duration and video-track sample (frame) count without audio-track confusion.
 */
export function parseMp4MetadataFromBytes(bytes: Uint8Array): ParsedMp4Metadata | null {
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  const state: {
    durationSeconds: number | null;
    timescale: number;
    videoTrackSamples: number;
    fallbackTrackSamples: number;
  } = {
    durationSeconds: null,
    timescale: 0,
    videoTrackSamples: 0,
    fallbackTrackSamples: 0,
  };

  interface TrackParseContext {
    handlerType: string | null;
    samples: number;
  }

  function walkBoxes(startOffset: number, endOffset: number, currentTrack: TrackParseContext | null): void {
    let offset = startOffset;
    const safeEnd = Math.min(endOffset, bytes.byteLength);

    while (offset + 8 <= safeEnd) {
      const rawSize = view.getUint32(offset, false);
      const type = String.fromCharCode(
        bytes[offset + 4],
        bytes[offset + 5],
        bytes[offset + 6],
        bytes[offset + 7]
      );

      let headerSize = 8;
      let boxSize = rawSize;

      if (rawSize === 1) {
        if (offset + 16 > safeEnd) break;
        const hi = view.getUint32(offset + 8, false);
        const lo = view.getUint32(offset + 12, false);
        boxSize = hi * 4294967296 + lo;
        headerSize = 16;
      } else if (rawSize === 0) {
        boxSize = safeEnd - offset;
      }

      if (boxSize < headerSize || offset + boxSize > safeEnd) {
        break;
      }

      const payloadStart = offset + headerSize;
      const boxEnd = offset + boxSize;

      if (type === 'mvhd' && payloadStart + 20 <= boxEnd) {
        const version = bytes[payloadStart];
        if (version === 0 && payloadStart + 20 <= boxEnd) {
          const ts = view.getUint32(payloadStart + 12, false);
          const dur = view.getUint32(payloadStart + 16, false);
          if (ts > 0 && dur > 0) {
            state.timescale = ts;
            state.durationSeconds = dur / ts;
          }
        } else if (version === 1 && payloadStart + 32 <= boxEnd) {
          const ts = view.getUint32(payloadStart + 20, false);
          const durHi = view.getUint32(payloadStart + 24, false);
          const durLo = view.getUint32(payloadStart + 28, false);
          const dur = durHi * 4294967296 + durLo;
          if (ts > 0 && dur > 0) {
            state.timescale = ts;
            state.durationSeconds = dur / ts;
          }
        }
      } else if (type === 'hdlr' && currentTrack && payloadStart + 12 <= boxEnd) {
        currentTrack.handlerType = String.fromCharCode(
          bytes[payloadStart + 8],
          bytes[payloadStart + 9],
          bytes[payloadStart + 10],
          bytes[payloadStart + 11]
        );
      } else if (type === 'stts' && payloadStart + 8 <= boxEnd) {
        const entryCount = view.getUint32(payloadStart + 4, false);
        let cursor = payloadStart + 8;
        let sampleTotal = 0;
        for (let i = 0; i < entryCount && cursor + 8 <= boxEnd; i++) {
          const sampleCount = view.getUint32(cursor, false);
          sampleTotal += sampleCount;
          cursor += 8;
        }
        if (currentTrack) {
          currentTrack.samples = Math.max(currentTrack.samples, sampleTotal);
        } else if (sampleTotal > state.fallbackTrackSamples) {
          state.fallbackTrackSamples = sampleTotal;
        }
      } else if (type === 'trak') {
        const trackCtx: TrackParseContext = { handlerType: null, samples: 0 };
        walkBoxes(payloadStart, boxEnd, trackCtx);
        if (trackCtx.handlerType === 'vide' && trackCtx.samples > state.videoTrackSamples) {
          state.videoTrackSamples = trackCtx.samples;
        } else if (trackCtx.handlerType !== 'soun' && trackCtx.samples > state.fallbackTrackSamples) {
          state.fallbackTrackSamples = trackCtx.samples;
        }
      } else if (CONTAINER_BOX_TYPES.has(type)) {
        walkBoxes(payloadStart, boxEnd, currentTrack);
      }

      offset = boxEnd;
    }
  }

  walkBoxes(0, bytes.byteLength, null);

  if (
    state.durationSeconds === null ||
    !Number.isFinite(state.durationSeconds) ||
    state.durationSeconds <= 0
  ) {
    return null;
  }

  const roundedDuration = Number(state.durationSeconds.toFixed(3));
  const bestSamples = state.videoTrackSamples > 0 ? state.videoTrackSamples : state.fallbackTrackSamples;
  const frameCount = bestSamples > 0 ? bestSamples : undefined;
  const fps =
    frameCount && state.durationSeconds > 0
      ? Number((frameCount / state.durationSeconds).toFixed(2))
      : undefined;

  return {
    durationSeconds: roundedDuration,
    timescale: state.timescale,
    frameCount,
    fps,
  };
}

/**
 * Probes an HTMLVideoElement in the browser to read actual decoded media duration and verify playability.
 */
export function probeBrowserVideoDuration(
  videoUrl: string,
  timeoutMs = 10_000
): Promise<number | null> {
  if (typeof document === 'undefined') {
    return Promise.resolve(null);
  }

  return new Promise((resolve) => {
    const video = document.createElement('video');
    let settled = false;

    const finish = (val: number | null) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      video.removeAttribute('src');
      video.load();
      resolve(val);
    };

    const timer = setTimeout(() => finish(null), timeoutMs);

    video.preload = 'metadata';
    video.muted = true;
    video.playsInline = true;

    video.onloadedmetadata = () => {
      if (Number.isFinite(video.duration) && video.duration > 0) {
        finish(Number(video.duration.toFixed(3)));
        return;
      }
      // Handle WebM MediaRecorder streams that seek to reveal real duration
      video.currentTime = 1e6;
    };

    video.ondurationchange = () => {
      if (Number.isFinite(video.duration) && video.duration > 0 && video.duration < 1e5) {
        finish(Number(video.duration.toFixed(3)));
      }
    };

    video.onerror = () => finish(null);
    video.src = videoUrl;
  });
}

/**
 * Checks whether a measured video file duration genuinely matches the requested option
 * within normal codec frame-boundary tolerance (e.g., 97 frames @ 24fps = 4.04s for 4s).
 */
export function isDurationWithinTolerance(
  actualSeconds: number,
  requestedSeconds: ClipDurationOption,
  toleranceSeconds = 0.85
): boolean {
  return Math.abs(actualSeconds - requestedSeconds) <= toleranceSeconds;
}
